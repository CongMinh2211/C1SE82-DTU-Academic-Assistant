-- Cloud schema v1; applied explicitly, never during a request.
CREATE EXTENSION IF NOT EXISTS unaccent;
CREATE EXTENSION IF NOT EXISTS vector;
CREATE OR REPLACE FUNCTION search_fold(value text) RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$ SELECT lower(unaccent(coalesce(value,''))) $$;
CREATE TABLE IF NOT EXISTS documents (
      id TEXT PRIMARY KEY, title TEXT NOT NULL, topic TEXT NOT NULL,
      source_kind TEXT NOT NULL, source_url TEXT, original_name TEXT,
      scope TEXT NOT NULL DEFAULT '', active_revision TEXT, deleted_at TEXT,
      created_at TEXT NOT NULL, updated_at TEXT NOT NULL
    );
CREATE TABLE IF NOT EXISTS revisions (
      id TEXT PRIMARY KEY, document_id TEXT NOT NULL REFERENCES documents(id),
      version BIGINT NOT NULL, sha256 TEXT NOT NULL, raw_path TEXT NOT NULL,
      mime TEXT NOT NULL, title_snapshot TEXT NOT NULL, scope_snapshot TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'queued',
      pages_json TEXT, chunk_count BIGINT DEFAULT 0, error TEXT,
      created_at TEXT NOT NULL, published_at TEXT, source_url TEXT,
      effective_from DATE,
      effective_to DATE,
      UNIQUE(document_id, version)
    );
CREATE TABLE IF NOT EXISTS chunks (
      id TEXT PRIMARY KEY, revision_id TEXT NOT NULL REFERENCES revisions(id),
      document_id TEXT NOT NULL REFERENCES documents(id), page BIGINT NOT NULL,
      page_end BIGINT NOT NULL, section TEXT NOT NULL, text TEXT NOT NULL,
      search_text TEXT NOT NULL, metadata_json TEXT NOT NULL
    , _ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE IF NOT EXISTS jobs (
      id TEXT PRIMARY KEY, revision_id TEXT NOT NULL REFERENCES revisions(id),
      status TEXT NOT NULL DEFAULT 'queued', stage TEXT NOT NULL DEFAULT 'queued',
      progress BIGINT NOT NULL DEFAULT 0, attempts BIGINT NOT NULL DEFAULT 0,
      error TEXT, lease_until BIGINT, started_at TEXT, finished_at TEXT,
      created_at TEXT NOT NULL
    );
CREATE TABLE IF NOT EXISTS conversations (
      id TEXT PRIMARY KEY, user_id TEXT NOT NULL, title TEXT NOT NULL,
      created_at TEXT NOT NULL, updated_at TEXT NOT NULL
    , deleted_at TEXT);
CREATE TABLE IF NOT EXISTS messages (
      id TEXT PRIMARY KEY, conversation_id TEXT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
      role TEXT NOT NULL, content TEXT NOT NULL DEFAULT '', status TEXT NOT NULL,
      citations_json TEXT NOT NULL DEFAULT '[]', trace_id TEXT, created_at TEXT NOT NULL
    , _ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY);
CREATE TABLE IF NOT EXISTS feedback (
      id TEXT PRIMARY KEY, user_id TEXT NOT NULL, message_id TEXT REFERENCES messages(id) ON DELETE SET NULL,
      rating BIGINT NOT NULL, category TEXT NOT NULL, content TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending', resolution TEXT, resolved_by TEXT,
      created_at TEXT NOT NULL, resolved_at TEXT
    );
CREATE TABLE IF NOT EXISTS faqs (
      id TEXT PRIMARY KEY, question TEXT NOT NULL, answer TEXT NOT NULL,
      topic TEXT NOT NULL, source_chunk TEXT REFERENCES chunks(id),
      status TEXT NOT NULL DEFAULT 'draft', updated_by TEXT NOT NULL, updated_at TEXT NOT NULL
    );
CREATE TABLE IF NOT EXISTS audit (
      id TEXT PRIMARY KEY, actor_id TEXT, action TEXT NOT NULL, entity_id TEXT,
      detail TEXT NOT NULL DEFAULT '{}', created_at TEXT NOT NULL
    );
CREATE TABLE IF NOT EXISTS traces (
      id TEXT PRIMARY KEY, user_id TEXT NOT NULL, conversation_id TEXT NOT NULL,
      question TEXT NOT NULL, status TEXT NOT NULL, retrieval_json TEXT NOT NULL DEFAULT '[]',
      model TEXT, latency_ms BIGINT, reason TEXT, created_at TEXT NOT NULL
    );
CREATE TABLE IF NOT EXISTS rate_limits (
      key TEXT PRIMARY KEY, count BIGINT NOT NULL, expires_at BIGINT NOT NULL
    );
CREATE TABLE IF NOT EXISTS chat_leases (user_id TEXT PRIMARY KEY, expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS chunks_fts (id TEXT PRIMARY KEY, text TEXT NOT NULL, search_vector tsvector GENERATED ALWAYS AS (to_tsvector('simple',text)) STORED);
CREATE INDEX IF NOT EXISTS chunks_fts_search ON chunks_fts USING gin(search_vector);
CREATE INDEX IF NOT EXISTS chunks_revision ON chunks(revision_id);
CREATE UNIQUE INDEX IF NOT EXISTS one_live_job ON jobs(revision_id) WHERE status IN ('queued','running');
CREATE INDEX IF NOT EXISTS conversation_owner ON conversations(user_id,updated_at);
CREATE INDEX IF NOT EXISTS message_conversation ON messages(conversation_id,created_at);
CREATE INDEX IF NOT EXISTS audit_time ON audit(created_at);
CREATE INDEX IF NOT EXISTS "session_userId_idx" on "session" ("userId");
CREATE INDEX IF NOT EXISTS "account_userId_idx" on "account" ("userId");
CREATE INDEX IF NOT EXISTS "verification_identifier_idx" on "verification" ("identifier");
CREATE TABLE IF NOT EXISTS cloud_migrations(id text PRIMARY KEY, detail_json text NOT NULL, completed_at text NOT NULL);
CREATE TABLE IF NOT EXISTS upload_grants(id text PRIMARY KEY, user_id text NOT NULL, pathname text NOT NULL UNIQUE, filename text NOT NULL, metadata_json text NOT NULL, expires_at bigint NOT NULL, revision_id text);

ALTER TABLE upload_grants ADD COLUMN IF NOT EXISTS lease_until bigint;

CREATE TABLE IF NOT EXISTS cloud_index_runs(revision_id text PRIMARY KEY REFERENCES revisions(id),cursor bigint NOT NULL DEFAULT 0,prepared boolean NOT NULL DEFAULT false);
